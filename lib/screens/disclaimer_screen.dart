import 'package:flutter/material.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'checklist_screen.dart';

class DisclaimerScreen extends StatefulWidget {
  const DisclaimerScreen({super.key});

  @override
  State<DisclaimerScreen> createState() => _DisclaimerScreenState();
}

class _DisclaimerScreenState extends State<DisclaimerScreen> {
  bool _agreed = false;

  Future<void> _accept() async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setBool('disclaimer_accepted', true);
    if (!mounted) return;
    Navigator.pushReplacement(
      context,
      MaterialPageRoute(builder: (_) => const ChecklistScreen()),
    );
  }

  @override
  Widget build(BuildContext context) {
    final teal = Theme.of(context).colorScheme.primary;

    return Scaffold(
      backgroundColor: Theme.of(context).colorScheme.surface,
      body: SafeArea(
        child: SingleChildScrollView(
          padding: const EdgeInsets.all(24),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              const SizedBox(height: 16),

              // App name
              Text(
                'DocPrep',
                style: TextStyle(fontSize: 28, fontWeight: FontWeight.w600, color: teal),
              ),
              const SizedBox(height: 4),
              Text(
                'Before you get started, please read this carefully.',
                style: TextStyle(fontSize: 14, color: Colors.grey.shade600),
              ),
              const SizedBox(height: 28),

              // Disclaimer card
              Container(
                padding: const EdgeInsets.all(20),
                decoration: BoxDecoration(
                  color: Colors.grey.shade50,
                  border: Border.all(color: Colors.grey.shade200),
                  borderRadius: BorderRadius.circular(12),
                ),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [

                    _section(
                      context,
                      icon: Icons.medical_services_outlined,
                      title: 'Not a medical tool',
                      body:
                          'DocPrep is designed to help you communicate more effectively with your healthcare provider. It does not provide medical advice, diagnosis, or treatment of any kind. Nothing generated by this app should be interpreted as a medical opinion or clinical recommendation.',
                    ),
                    const SizedBox(height: 20),

                    _section(
                      context,
                      icon: Icons.emergency_outlined,
                      title: 'Medical emergencies',
                      body:
                          'If you are experiencing a medical emergency, call 911 or go to your nearest emergency room immediately. Do not use this app in an emergency situation. If you are concerned about your safety or the safety of someone else, seek emergency medical care right away.',
                      urgent: true,
                    ),
                    const SizedBox(height: 20),

                    _section(
                      context,
                      icon: Icons.balance_outlined,
                      title: 'Limitation of liability',
                      body:
                          'DocPrep and its developers are not liable for any outcomes resulting from the use of this application, including but not limited to medical decisions made based on generated scripts. This app is provided as-is to help patients advocate for themselves in medical settings. Use of this app does not create a medical or legal relationship of any kind.',
                    ),
                    const SizedBox(height: 20),

                    _section(
                      context,
                      icon: Icons.volunteer_activism_outlined,
                      title: 'What this app is for',
                      body:
                          'DocPrep is here to help you find the words to express your concerns, questions, and needs during a doctor\'s appointment. It is a communication aid — nothing more. Always follow the guidance of your licensed healthcare provider.',
                    ),
                    const SizedBox(height: 20),

                    _section(
                      context,
                      icon: Icons.smart_toy_outlined,
                      title: 'This app uses AI — review everything',
                      body:
                          'DocPrep is powered by an AI model. AI can make mistakes, misinterpret your input, or generate language that does not accurately reflect your situation. Always review your script carefully before using it. Only use words and descriptions that truly reflect how you are feeling. Never present anything to your doctor that does not accurately describe your symptoms or experience.',
                      urgent: true,
                    ),
                  ],
                ),
              ),

              const SizedBox(height: 24),

              // Checkbox agreement
              GestureDetector(
                onTap: () => setState(() => _agreed = !_agreed),
                child: Row(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Checkbox(
                      value: _agreed,
                      onChanged: (val) => setState(() => _agreed = val ?? false),
                      activeColor: teal,
                      materialTapTargetSize: MaterialTapTargetSize.shrinkWrap,
                    ),
                    const SizedBox(width: 8),
                    Expanded(
                      child: Padding(
                        padding: const EdgeInsets.only(top: 10),
                        child: Text(
                          'I understand that DocPrep is not a medical tool, does not provide medical advice or diagnosis, and cannot be held liable for any outcomes. I will seek emergency services if needed.',
                          style: TextStyle(fontSize: 13, color: Colors.grey.shade700, height: 1.5),
                        ),
                      ),
                    ),
                  ],
                ),
              ),

              const SizedBox(height: 20),

              // Continue button
              SizedBox(
                width: double.infinity,
                child: ElevatedButton(
                  onPressed: _agreed ? _accept : null,
                  style: ElevatedButton.styleFrom(
                    minimumSize: const Size(double.infinity, 50),
                    shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(10)),
                    textStyle: const TextStyle(fontSize: 15, fontWeight: FontWeight.w500),
                  ),
                  child: const Text('I understand, continue'),
                ),
              ),

              const SizedBox(height: 12),
              Center(
                child: Text(
                  'You only need to agree once.',
                  style: TextStyle(fontSize: 12, color: Colors.grey.shade400),
                ),
              ),
              const SizedBox(height: 24),
            ],
          ),
        ),
      ),
    );
  }

  Widget _section(BuildContext context, {
    required IconData icon,
    required String title,
    required String body,
    bool urgent = false,
  }) {
    final teal = Theme.of(context).colorScheme.primary;
    return Row(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Container(
          margin: const EdgeInsets.only(top: 2),
          padding: const EdgeInsets.all(6),
          decoration: BoxDecoration(
            color: urgent ? Colors.red.shade50 : Colors.teal.shade50,
            borderRadius: BorderRadius.circular(8),
          ),
          child: Icon(icon, size: 18, color: urgent ? Colors.red.shade600 : teal),
        ),
        const SizedBox(width: 12),
        Expanded(
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Text(title, style: TextStyle(fontSize: 14, fontWeight: FontWeight.w600, color: urgent ? Colors.red.shade700 : Colors.grey.shade800)),
              const SizedBox(height: 4),
              Text(body, style: TextStyle(fontSize: 13, color: Colors.grey.shade600, height: 1.5)),
            ],
          ),
        ),
      ],
    );
  }
}
